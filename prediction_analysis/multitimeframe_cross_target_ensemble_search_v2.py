#!/usr/bin/env python3
"""Cross-target cross-timeframe meta-model search (v2, strict walk-forward).

This script is analysis-only. It consumes probability rows generated by
`multitimeframe_direction_ensemble_analysis.py` and trains a two-head meta-model:

- Head A: breakfree 3-class (UP/DOWN/HOLD)
- Head B: 4class direction 2-class (UP/DOWN)

Final prediction rule is locked:
1) if breakfree predicts HOLD -> HOLD
2) else if breakfree direction == 4class direction -> that direction
3) else -> HOLD

All calibration and fitting for batch `t` uses only history `< t`.
"""

