def _load_candidate_meta(path: Path) -> pl.DataFrame:
    data = json.loads(path.read_text(encoding="utf-8"))
    missing = sorted(UNITS_REQUIRED - set(data.keys()))
    if missing:
        raise ValueError(f"Missing required units in candidate_sets_by_unit.json: {missing}")

    rows: list[dict[str, Any]] = []
    for unit in sorted(UNITS_REQUIRED):
        entry = data[unit]
        action_keys = [str(v) for v in entry.get("action_keys", [])]
        if len(action_keys) != 12:
            raise ValueError(f"{unit} has {len(action_keys)} candidates, expected 12")
        if len(set(action_keys)) != 12:
            raise ValueError(f"{unit} has duplicate candidates")
        wins = {str(k): int(v) for k, v in entry.get("winner_wins", {}).items()}
        tf, target = unit.split("/", 1)
        for ak in sorted(action_keys):
            rows.append(
                {
                    "unit": unit,
                    "timeframe": tf,
                    "target": target,
                    "action_key": ak,
                    "winner_wins": int(wins.get(ak, 0)),
                    "candidate_id": f"{unit}::{ak}",
                }
            )

    meta = pl.DataFrame(rows).sort(["unit", "action_key"])
    if meta.height != 72:
        raise ValueError(f"Candidate universe size is {meta.height}, expected 72")
    return meta.with_row_index("candidate_idx")


def _map_truth_breakfree(y: int) -> int:
    if y == 0:
        return UP
    if y == 1:
        return DOWN
    return HOLD


def _map_truth_4dir(y: int) -> int:
    if y in (2, 3):
        return UP
    if y in (0, 1):
        return DOWN
    return HOLD


def _compose_final_truth(truth_breakfree: np.ndarray, truth_4dir: np.ndarray) -> np.ndarray:
    out = np.full(truth_breakfree.shape[0], HOLD, dtype=np.int16)
    hold_mask = truth_breakfree == HOLD
    up_agree = (truth_breakfree == UP) & (truth_4dir == UP)
    dn_agree = (truth_breakfree == DOWN) & (truth_4dir == DOWN)
    out[hold_mask] = HOLD
    out[up_agree] = UP
    out[dn_agree] = DOWN
    # all mismatches are HOLD by design
    return out


def _build_prepared_data(
    *,
    unit_rows: pl.DataFrame,
    candidate_meta: pl.DataFrame,
    out_dir: Path,
    expected_batches: int,
    strict_label_domain: bool,
) -> PreparedData:
    if int(expected_batches) <= 0:
        raise ValueError(f"expected_batches must be > 0, got {expected_batches}")

    report: dict[str, Any] = {
        "status": "running",
        "validations": {},
        "counts": {},
        "samples": {},
    }

    required_cols = {
        "pred_batch",
        "timestamp",
        "batch_id",
        "unit",
        "timeframe",
        "target",
        "action_key",
        "y_true",
        "prob_class_0",
        "prob_class_1",
        "prob_class_2",
    }
    missing_cols = sorted(required_cols - set(unit_rows.columns))
    if missing_cols:
        raise ValueError(f"Missing required input columns: {missing_cols}")

    if "prob_class_3" not in unit_rows.columns:
        unit_rows = unit_rows.with_columns(pl.lit(0.0).alias("prob_class_3"))
    if "anchor_15m_ts" not in unit_rows.columns:
        unit_rows = unit_rows.with_columns(
            pl.col("timestamp")
            .dt.truncate("15m")
            .cast(pl.Datetime("us"), strict=False)
            .alias("anchor_15m_ts")
        )
    else:
        unit_rows = unit_rows.with_columns(
            pl.col("anchor_15m_ts").cast(pl.Datetime("us"), strict=False)
        )

    unit_rows = unit_rows.with_columns(
        pl.concat_str([pl.col("unit"), pl.lit("::"), pl.col("action_key")]).alias(
            "candidate_id"
        )
    )
    candidate_ids = set(candidate_meta["candidate_id"].to_list())
    unit_rows = unit_rows.filter(pl.col("candidate_id").is_in(list(candidate_ids)))
    report["counts"]["unit_rows_filtered"] = int(unit_rows.height)

    # Pre-alignment per-candidate per-batch row integrity.
    pre_counts = (
        unit_rows.group_by(["unit", "timeframe", "target", "action_key", "pred_batch"])
        .len()
        .with_columns(
            pl.col("timeframe")
            .replace_strict(ROW_EXPECTED_BY_TIMEFRAME_BATCH)
            .cast(pl.Int64)
            .alias("expected_rows")
        )
        .with_columns((pl.col("len") == pl.col("expected_rows")).alias("row_count_match"))
    )
    pre_bad = pre_counts.filter(~pl.col("row_count_match"))
    report["counts"]["precheck_rows"] = int(pre_counts.height)
    report["counts"]["precheck_bad_rows"] = int(pre_bad.height)
    report["validations"]["pre_batch_row_count_match"] = bool(pre_bad.is_empty())
    if not pre_bad.is_empty():
        report["status"] = "failed"
        report["samples"]["pre_batch_row_mismatch"] = pre_bad.head(50).to_dicts()
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError(
            "Data integrity failed: pre-alignment rows per candidate/batch do not match "
            "expected {1m:240,5m:48,15m:16}."
        )

    # Truth anchors from 15m units.
    key_cols = ["pred_batch", "anchor_15m_ts"]
    truth_breakfree_raw = (
        unit_rows.filter(pl.col("unit") == "15m/target_breakfree")
        .group_by(key_cols)
        .agg(pl.col("y_true").first().alias("y_true_breakfree"))
    )
    truth_4_raw = (
        unit_rows.filter(pl.col("unit") == "15m/target_4class")
        .group_by(key_cols)
        .agg(pl.col("y_true").first().alias("y_true_4class"))
    )

    if strict_label_domain:
        bad_break = truth_breakfree_raw.filter(~pl.col("y_true_breakfree").is_in([0, 1, 2]))
        bad_4 = truth_4_raw.filter(~pl.col("y_true_4class").is_in([0, 1, 2, 3]))
        report["counts"]["invalid_truth_breakfree_rows"] = int(bad_break.height)
        report["counts"]["invalid_truth_4class_rows"] = int(bad_4.height)
        report["validations"]["truth_breakfree_domain_valid"] = bool(bad_break.is_empty())
        report["validations"]["truth_4class_domain_valid"] = bool(bad_4.is_empty())
        if not bad_break.is_empty() or not bad_4.is_empty():
            report["status"] = "failed"
            if not bad_break.is_empty():
                report["samples"]["invalid_truth_breakfree"] = bad_break.head(50).to_dicts()
            if not bad_4.is_empty():
                report["samples"]["invalid_truth_4class"] = bad_4.head(50).to_dicts()
            _write_json(out_dir / "data_integrity_report.json", report)
            raise IntegrityError(
                "Data integrity failed: truth labels out of domain "
                "(breakfree must be {0,1,2}; 4class must be {0,1,2,3})."
            )

    truth_breakfree = truth_breakfree_raw.with_columns(
        pl.col("y_true_breakfree")
        .map_elements(lambda v: _map_truth_breakfree(int(v)), return_dtype=pl.Int16)
        .alias("truth_breakfree")
    ).select(key_cols + ["truth_breakfree"])
    truth_4 = truth_4_raw.with_columns(
        pl.col("y_true_4class")
        .map_elements(lambda v: _map_truth_4dir(int(v)), return_dtype=pl.Int16)
        .alias("truth_4dir")
    ).select(key_cols + ["truth_4dir"])
    anchor_df = (
        truth_breakfree.join(truth_4, on=key_cols, how="inner")
        .sort(key_cols)
        .with_row_index("anchor_idx")
    )

    if anchor_df.is_empty():
        report["status"] = "failed"
        report["validations"]["anchor_truth_non_empty"] = False
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError("Data integrity failed: anchor truth table is empty.")

    batch_order = anchor_df["pred_batch"].unique(maintain_order=True).to_list()
    report["counts"]["expected_batches"] = int(expected_batches)
    report["counts"]["discovered_batches"] = int(len(batch_order))
    report["validations"]["batch_count_matches_expected"] = (
        int(len(batch_order)) == int(expected_batches)
    )
    if len(batch_order) > 0:
        min_batch = int(min(batch_order))
        expected_set = set(range(min_batch, min_batch + int(expected_batches)))
        actual_set = {int(v) for v in batch_order}
        missing_batches = sorted(expected_set - actual_set)
        extra_batches = sorted(actual_set - expected_set)
        report["samples"]["batch_id_span_check"] = {
            "min_batch": min_batch,
            "max_batch": int(max(batch_order)),
            "missing_batches_head": missing_batches[:50],
            "extra_batches_head": extra_batches[:50],
            "missing_count": int(len(missing_batches)),
            "extra_count": int(len(extra_batches)),
        }
    if int(len(batch_order)) != int(expected_batches):
        report["status"] = "failed"
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError(
            f"Data integrity failed: discovered batches={len(batch_order)} "
            f"expected={expected_batches}."
        )

    anchor_per_batch = anchor_df.group_by("pred_batch").len()
    bad_anchor_counts = anchor_per_batch.filter(pl.col("len") != 16)
    report["counts"]["anchor_rows"] = int(anchor_df.height)
    report["counts"]["anchor_batches"] = int(len(batch_order))
    report["validations"]["anchor_rows_per_batch_is_16"] = bool(bad_anchor_counts.is_empty())
    report["counts"]["anchor_bad_batches"] = int(bad_anchor_counts.height)
    if not bad_anchor_counts.is_empty():
        report["status"] = "failed"
        report["samples"]["anchor_bad_batches"] = bad_anchor_counts.head(50).to_dicts()
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError("Data integrity failed: each batch must have exactly 16 anchors.")

    expected_anchor_rows = int(len(batch_order) * 16)
    report["counts"]["anchor_rows_expected"] = expected_anchor_rows
    report["validations"]["anchor_total_matches_expected"] = (
        int(anchor_df.height) == expected_anchor_rows
    )
    if int(anchor_df.height) != expected_anchor_rows:
        report["status"] = "failed"
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError(
            f"Data integrity failed: anchor rows={anchor_df.height} expected={expected_anchor_rows}."
        )

    # same_period_close alignment only.
    align_key = ["pred_batch", "anchor_15m_ts", "unit", "action_key"]
    aligned_df = (
        unit_rows.sort(
            ["pred_batch", "anchor_15m_ts", "unit", "action_key", "timestamp", "batch_id"],
            descending=[False, False, False, False, False, False],
        )
        .with_columns(
            [
                pl.col("timestamp").cum_count().over(align_key).alias("row_pos"),
                pl.len().over(align_key).alias("row_count"),
                pl.col("timeframe")
                .replace_strict(ROW_EXPECTED_BY_TIMEFRAME_ANCHOR)
                .cast(pl.Int64)
                .alias("row_count_expected"),
            ]
        )
        .filter(pl.col("row_pos") == pl.col("row_count_expected"))
        .with_columns((pl.col("row_count") == pl.col("row_count_expected")).alias("row_count_match"))
        .join(
            candidate_meta.select(
                ["candidate_idx", "candidate_id", "unit", "action_key", "target", "timeframe"]
            ),
            on=["candidate_id", "unit", "action_key", "target", "timeframe"],
            how="inner",
        )
        .join(anchor_df.select(["anchor_idx", "pred_batch", "anchor_15m_ts"]), on=key_cols, how="inner")
        .select(
            [
                "anchor_idx",
                "pred_batch",
                "anchor_15m_ts",
                "candidate_idx",
                "candidate_id",
                "unit",
                "timeframe",
                "target",
                "action_key",
                "row_count",
                "row_count_expected",
                "row_count_match",
                "prob_class_0",
                "prob_class_1",
                "prob_class_2",
                "prob_class_3",
            ]
        )
        .sort(["anchor_idx", "candidate_idx"])
        .unique(subset=["anchor_idx", "candidate_idx"], keep="first")
    )

    # Hard checks for alignment completeness.
    bad_align_counts = aligned_df.filter(~pl.col("row_count_match"))
    report["counts"]["aligned_rows"] = int(aligned_df.height)
    report["counts"]["aligned_bad_row_count"] = int(bad_align_counts.height)
    report["validations"]["aligned_row_count_match"] = bool(bad_align_counts.is_empty())
    if not bad_align_counts.is_empty():
        report["status"] = "failed"
        report["samples"]["aligned_bad_row_count"] = bad_align_counts.head(50).to_dicts()
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError(
            "Data integrity failed: same_period_close row counts do not match expected {15,3,1}."
        )

    expected_pairs = (
        anchor_df.select(["anchor_idx", "pred_batch", "anchor_15m_ts"])
        .join(candidate_meta.select(["candidate_idx", "candidate_id", "unit", "action_key"]), how="cross")
        .select(
            [
                "anchor_idx",
                "pred_batch",
                "anchor_15m_ts",
                "candidate_idx",
                "candidate_id",
                "unit",
                "action_key",
            ]
        )
    )
    got_pairs = aligned_df.select(
        [
            "anchor_idx",
            "pred_batch",
            "anchor_15m_ts",
            "candidate_idx",
            "candidate_id",
            "unit",
            "action_key",
        ]
    )
    missing_pairs = expected_pairs.join(
        got_pairs,
        on=[
            "anchor_idx",
            "pred_batch",
            "anchor_15m_ts",
            "candidate_idx",
            "candidate_id",
            "unit",
            "action_key",
        ],
        how="anti",
    )
    report["counts"]["expected_anchor_candidate_rows"] = int(expected_pairs.height)
    report["counts"]["missing_anchor_candidate_rows"] = int(missing_pairs.height)
    report["validations"]["anchor_candidate_completeness"] = bool(missing_pairs.is_empty())
    if not missing_pairs.is_empty():
        report["status"] = "failed"
        report["samples"]["missing_anchor_candidate_rows"] = missing_pairs.head(50).to_dicts()
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError(
            "Data integrity failed: missing aligned rows for required "
            "(pred_batch, anchor_15m_ts, unit, action_key)."
        )

    # Add directional probabilities for diagnostics artifact.
    aligned_df = aligned_df.with_columns(
        [
            pl.when(pl.col("target") == TARGET_4CLASS)
            .then(pl.col("prob_class_2") + pl.col("prob_class_3"))
            .otherwise(pl.col("prob_class_0"))
            .cast(pl.Float32)
            .alias("p_up"),
            pl.when(pl.col("target") == TARGET_4CLASS)
            .then(pl.col("prob_class_0") + pl.col("prob_class_1"))
            .otherwise(pl.col("prob_class_1"))
            .cast(pl.Float32)
            .alias("p_down"),
            pl.when(pl.col("target") == TARGET_4CLASS)
            .then(pl.lit(0.0))
            .otherwise(pl.col("prob_class_2"))
            .cast(pl.Float32)
            .alias("p_hold"),
        ]
    )

    # Build labels.
    truth_break_arr = anchor_df["truth_breakfree"].to_numpy().astype(np.int16, copy=False)
    truth_4_arr = anchor_df["truth_4dir"].to_numpy().astype(np.int16, copy=False)
    truth_final_arr = _compose_final_truth(truth_break_arr, truth_4_arr)
    anchor_df = anchor_df.with_columns(pl.Series("truth_final", truth_final_arr))

    # Build wide feature matrix.
    n_anchor = int(anchor_df.height)
    n_cand = int(candidate_meta.height)
    p0 = np.full((n_anchor, n_cand), np.nan, dtype=np.float32)
    p1 = np.full((n_anchor, n_cand), np.nan, dtype=np.float32)
    p2 = np.full((n_anchor, n_cand), np.nan, dtype=np.float32)
    p3 = np.full((n_anchor, n_cand), np.nan, dtype=np.float32)

    a_idx = aligned_df["anchor_idx"].to_numpy()
    c_idx = aligned_df["candidate_idx"].to_numpy()
    p0[a_idx, c_idx] = aligned_df["prob_class_0"].cast(pl.Float32).to_numpy()
    p1[a_idx, c_idx] = aligned_df["prob_class_1"].cast(pl.Float32).to_numpy()
    p2[a_idx, c_idx] = aligned_df["prob_class_2"].cast(pl.Float32).to_numpy()
    p3_raw = aligned_df["prob_class_3"].cast(pl.Float32).to_numpy()
    p3[a_idx, c_idx] = np.where(np.isfinite(p3_raw), p3_raw, 0.0)

    if np.isnan(p0).any() or np.isnan(p1).any() or np.isnan(p2).any():
        report["status"] = "failed"
        report["validations"]["feature_core_probs_no_nan"] = False
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError("Data integrity failed: NaN detected in required base probabilities.")
    report["validations"]["feature_core_probs_no_nan"] = True

    target_by_idx = candidate_meta["target"].to_list()
    cand_id_by_idx = candidate_meta["candidate_id"].to_list()

    cols: list[np.ndarray] = []
    names: list[str] = []
    base_feature_count = 0

    for idx in range(n_cand):
        cid = _sanitize_name(str(cand_id_by_idx[idx]))
        if str(target_by_idx[idx]) == TARGET_4CLASS:
            for class_id, mat in enumerate((p0, p1, p2, p3)):
                cols.append(mat[:, idx].astype(np.float32, copy=False))
                names.append(f"{cid}__prob_c{class_id}")
                base_feature_count += 1
        else:
            for class_id, mat in enumerate((p0, p1, p2)):
                cols.append(mat[:, idx].astype(np.float32, copy=False))
                names.append(f"{cid}__prob_c{class_id}")
                base_feature_count += 1

    if base_feature_count != 252:
        report["status"] = "failed"
        report["counts"]["base_feature_count"] = int(base_feature_count)
        _write_json(out_dir / "data_integrity_report.json", report)
        raise IntegrityError(
            f"Base feature count is {base_feature_count}, expected 252 "
            "(4class:4*36 + breakfree:3*36)."
        )

    # Optional derived features.
    for idx in range(n_cand):
        cid = _sanitize_name(str(cand_id_by_idx[idx]))
        if str(target_by_idx[idx]) == TARGET_4CLASS:
            up = p2[:, idx] + p3[:, idx]
            down = p0[:, idx] + p1[:, idx]
            probs = np.clip(np.stack([p0[:, idx], p1[:, idx], p2[:, idx], p3[:, idx]], axis=1), 1e-12, 1.0)
            entropy = -np.sum(probs * np.log(probs), axis=1) / math.log(4.0)
        else:
            up = p0[:, idx]
            down = p1[:, idx]
            probs = np.clip(np.stack([p0[:, idx], p1[:, idx], p2[:, idx]], axis=1), 1e-12, 1.0)
            entropy = -np.sum(probs * np.log(probs), axis=1) / math.log(3.0)
        dir_score = up - down
        availability = np.ones_like(dir_score, dtype=np.float32)

        cols.append(dir_score.astype(np.float32, copy=False))
        names.append(f"{cid}__dir_score")
        cols.append(entropy.astype(np.float32, copy=False))
        names.append(f"{cid}__entropy")
        cols.append(availability.astype(np.float32, copy=False))
        names.append(f"{cid}__availability")

    x = np.column_stack(cols).astype(np.float32, copy=False)

    feature_payload: dict[str, Any] = {
        "anchor_idx": anchor_df["anchor_idx"].to_numpy().astype(np.int32),
        "pred_batch": anchor_df["pred_batch"].to_numpy().astype(np.int64),
        "anchor_15m_ts": anchor_df["anchor_15m_ts"].to_list(),
        "truth_breakfree": truth_break_arr.astype(np.int16),
        "truth_4dir": truth_4_arr.astype(np.int16),
        "truth_final": truth_final_arr.astype(np.int16),
    }
    for j, name in enumerate(names):
        feature_payload[name] = x[:, j]
    feature_df = pl.DataFrame(feature_payload)

    batch_ranges: dict[int, tuple[int, int]] = {}
    for pb in batch_order:
        sdf = anchor_df.filter(pl.col("pred_batch") == int(pb))
        start = int(sdf["anchor_idx"].min())
        end = int(sdf["anchor_idx"].max()) + 1
        batch_ranges[int(pb)] = (start, end)

    report["status"] = "passed"
    report["counts"]["candidate_count"] = int(candidate_meta.height)
    report["counts"]["feature_count_total"] = int(len(names))
    report["counts"]["feature_count_base"] = int(base_feature_count)
    report["counts"]["feature_count_derived"] = int(len(names) - base_feature_count)
    report["validations"]["candidate_count_is_72"] = int(candidate_meta.height) == 72
    report["validations"]["feature_count_base_is_252"] = int(base_feature_count) == 252

    _write_json(out_dir / "data_integrity_report.json", report)

    return PreparedData(
        anchor_df=anchor_df,
        aligned_df=aligned_df,
        candidate_meta=candidate_meta,
        feature_df=feature_df,
        X=x,
        feature_names=names,
        y_breakfree=truth_break_arr.astype(np.int16),
        y_4dir=truth_4_arr.astype(np.int16),
        y_final=truth_final_arr.astype(np.int16),
        batch_order=[int(v) for v in batch_order],
        batch_ranges=batch_ranges,
        integrity_report=report,
    )


def _compute_confusion(y_true: np.ndarray, y_pred: np.ndarray) -> np.ndarray:
    conf = np.zeros((3, 3), dtype=np.int64)
    for t, p in zip(y_true.tolist(), y_pred.tolist()):
        if t in (UP, DOWN, HOLD) and p in (UP, DOWN, HOLD):
            conf[int(t), int(p)] += 1
    return conf


def _compute_standard_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, Any]:
    if y_true.size == 0:
        return {
            "eligible_count": 0,
            "covered_count": 0,
            "coverage": 0.0,
            "accuracy_covered": 0.0,
            "macro_f1": 0.0,
            "balanced_accuracy": 0.0,
            "directional_balanced_recall": 0.0,
            "precision_up": 0.0,
            "precision_down": 0.0,
            "precision_hold": 0.0,
            "recall_up": 0.0,
            "recall_down": 0.0,
            "recall_hold": 0.0,
            "f1_up": 0.0,
            "f1_down": 0.0,
            "f1_hold": 0.0,
            "confusion": np.zeros((3, 3), dtype=np.int64),
        }

    conf = _compute_confusion(y_true, y_pred)
    n = int(y_true.size)
    acc = float((y_true == y_pred).mean())

    precisions: dict[int, float] = {}
    recalls: dict[int, float] = {}
    f1s: dict[int, float] = {}

    for cls in (UP, DOWN, HOLD):
        i = int(cls)
        tp = float(conf[i, i])
        fp = float(conf[:, i].sum() - tp)
        fn = float(conf[i, :].sum() - tp)
        p = tp / (tp + fp) if tp + fp > 0 else 0.0
        r = tp / (tp + fn) if tp + fn > 0 else 0.0
        f1 = (2.0 * p * r / (p + r)) if p + r > 0 else 0.0
        precisions[cls] = p
        recalls[cls] = r
        f1s[cls] = f1

    macro_f1 = float(np.mean([f1s[UP], f1s[DOWN], f1s[HOLD]]))
    bal_acc = float(np.mean([recalls[UP], recalls[DOWN], recalls[HOLD]]))
    dir_bal = float(np.mean([recalls[UP], recalls[DOWN]]))

    return {
        "eligible_count": n,
        "covered_count": n,
        "coverage": 1.0,
        "accuracy_covered": acc,
        "macro_f1": macro_f1,
        "balanced_accuracy": bal_acc,
        "directional_balanced_recall": dir_bal,
        "precision_up": precisions[UP],
        "precision_down": precisions[DOWN],
        "precision_hold": precisions[HOLD],
        "recall_up": recalls[UP],
        "recall_down": recalls[DOWN],
        "recall_hold": recalls[HOLD],
        "f1_up": f1s[UP],
        "f1_down": f1s[DOWN],
        "f1_hold": f1s[HOLD],
        "confusion": conf,
    }


def _compute_custom_cost(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, Any]:
    if y_true.size == 0:
        return {
            "mean_cost": 0.0,
            "utility": 1.0,
            "cost_sum": 0.0,
            "count_correct": 0,
            "count_opposite_direction": 0,
            "count_hold_mismatch": 0,
        }
    correct = y_true == y_pred
    opposite = ((y_true == UP) & (y_pred == DOWN)) | ((y_true == DOWN) & (y_pred == UP))
    hold_mismatch = ~correct & ~opposite
    costs = np.where(correct, 0.0, np.where(opposite, 2.0, 1.0))
    mean_cost = float(costs.mean())
    utility = float(1.0 - mean_cost / 2.0)
    return {
        "mean_cost": mean_cost,
        "utility": utility,
        "cost_sum": float(costs.sum()),
        "count_correct": int(correct.sum()),
        "count_opposite_direction": int(opposite.sum()),
        "count_hold_mismatch": int(hold_mismatch.sum()),
    }


def _compute_batch_block_bootstrap_ci(
    final_pred_df: pl.DataFrame, *, seed: int, n_bootstrap: int = 500
) -> dict[str, Any]:
    if final_pred_df.is_empty() or n_bootstrap <= 0:
        return {
            "n_bootstrap": int(max(n_bootstrap, 0)),
            "macro_f1_ci95": [None, None],
            "mean_cost_ci95": [None, None],
            "macro_f1_median": None,
            "mean_cost_median": None,
        }

    grouped = (
        final_pred_df.sort(["pred_batch", "anchor_15m_ts"])
        .group_by("pred_batch", maintain_order=True)
        .agg(
            [
                pl.col("truth_final").alias("truth_final_list"),
                pl.col("pred_final").alias("pred_final_list"),
            ]
        )
    )
    truth_blocks = [np.asarray(v, dtype=np.int16) for v in grouped["truth_final_list"].to_list()]
    pred_blocks = [np.asarray(v, dtype=np.int16) for v in grouped["pred_final_list"].to_list()]
    n_blocks = len(truth_blocks)
    if n_blocks == 0:
        return {
            "n_bootstrap": int(max(n_bootstrap, 0)),
            "macro_f1_ci95": [None, None],
            "mean_cost_ci95": [None, None],
            "macro_f1_median": None,
            "mean_cost_median": None,
        }

    rng = np.random.default_rng(int(seed))
    macro_vals = np.zeros(int(n_bootstrap), dtype=np.float64)
    cost_vals = np.zeros(int(n_bootstrap), dtype=np.float64)
    for i in range(int(n_bootstrap)):
        draw_idx = rng.integers(0, n_blocks, size=n_blocks)
        y_true = np.concatenate([truth_blocks[int(j)] for j in draw_idx])
        y_pred = np.concatenate([pred_blocks[int(j)] for j in draw_idx])
        macro_vals[i] = float(_compute_standard_metrics(y_true, y_pred)["macro_f1"])
        cost_vals[i] = float(_compute_custom_cost(y_true, y_pred)["mean_cost"])

    return {
        "n_bootstrap": int(n_bootstrap),
        "macro_f1_ci95": [
            float(np.quantile(macro_vals, 0.025)),
            float(np.quantile(macro_vals, 0.975)),
        ],
        "mean_cost_ci95": [
            float(np.quantile(cost_vals, 0.025)),
            float(np.quantile(cost_vals, 0.975)),
        ],
        "macro_f1_median": float(np.quantile(macro_vals, 0.5)),
        "mean_cost_median": float(np.quantile(cost_vals, 0.5)),
    }


def _compose_final_prediction(pred_breakfree: np.ndarray, pred_4dir: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    out = np.full(pred_breakfree.shape[0], HOLD, dtype=np.int16)
    reason = np.full(pred_breakfree.shape[0], "conflict_hold", dtype=object)
    hold_mask = pred_breakfree == HOLD
    agree_up = (pred_breakfree == UP) & (pred_4dir == UP)
    agree_down = (pred_breakfree == DOWN) & (pred_4dir == DOWN)
    out[hold_mask] = HOLD
    out[agree_up] = UP
    out[agree_down] = DOWN
    reason[hold_mask] = "hold_from_breakfree"
    reason[agree_up | agree_down] = "agree_direction"
    return out, reason


def _get_batch_window(
    *,
    batch_order: list[int],
    current_batch_idx: int,
    lookback_batches: int,
) -> list[int]:
    history = batch_order[:current_batch_idx]
    if lookback_batches < 0:
        return history
    if lookback_batches >= len(history):
        return history
    return history[-lookback_batches:]


def _resolve_feasible_lookback_grid(lookback_grid: list[int], history_len: int) -> list[int]:
    if history_len <= 0:
        return []
    out: list[int] = []
    seen: set[int] = set()
    for lb in lookback_grid:
        v = int(lb)
        if v < 0 or v <= history_len:
            if v not in seen:
                out.append(v)
                seen.add(v)
    if not out:
        out = [int(history_len)]
    return out


def _split_train_val_batches(history_batches: list[int], val_tail_ratio: float) -> tuple[list[int], list[int]]:
    n = len(history_batches)
    if n < 2:
        return [], []
    n_val = int(round(n * val_tail_ratio))
    n_val = max(1, n_val)
    n_val = min(n - 1, n_val)
    train_b = history_batches[:-n_val]
    val_b = history_batches[-n_val:]
    return train_b, val_b


def _batches_to_indices(batch_ranges: dict[int, tuple[int, int]], batches: list[int]) -> np.ndarray:
    if not batches:
        return np.empty(0, dtype=np.int64)
    parts = [np.arange(batch_ranges[int(b)][0], batch_ranges[int(b)][1], dtype=np.int64) for b in batches]
    return np.concatenate(parts) if parts else np.empty(0, dtype=np.int64)


def _fit_selector_tree(
    *,
    x_train: np.ndarray,
    y_train: np.ndarray,
    head_name: str,
    gpu_devices: str,
    seed: int,
) -> np.ndarray:
    loss_function = "MultiClass" if head_name == "breakfree" else "Logloss"
    model = CatBoostClassifier(
        loss_function=loss_function,
        iterations=120,
        depth=4,
        learning_rate=0.05,
        l2_leaf_reg=3.0,
        random_seed=int(seed),
        task_type="GPU",
        devices=str(gpu_devices),
        allow_writing_files=False,
        verbose=False,
    )
    model.fit(x_train, y_train)
    imp = model.get_feature_importance()
    return np.asarray(imp, dtype=np.float64)


def _select_features(
    *,
    method: str,
    x_train: np.ndarray,
    y_train: np.ndarray,
    feature_names: list[str],
    seed: int,
    head_name: str,
    gpu_devices: str,
    fs_params: dict[str, Any],
) -> SelectionResult:
    n_feat = int(x_train.shape[1])
    all_idx = np.arange(n_feat, dtype=np.int32)

    if method == "none":
        return SelectionResult(
            selected_idx=all_idx,
            selected_feature_names=feature_names.copy(),
            meta={"selector": "none", "selected_count": n_feat},
            score_vector=None,
        )

    if method == "l1_nonzero":
        c = float(fs_params.get("fs_l1_c", 1.0))
        min_keep = int(fs_params.get("fs_min_keep", 16))

        scaler = StandardScaler(copy=True, with_mean=True, with_std=True)
        x_sc = scaler.fit_transform(x_train)
        clf = LogisticRegression(
            C=c,
            l1_ratio=1.0,
            solver="saga",
            max_iter=1500,
            random_state=int(seed),
        )
        clf.fit(x_sc, y_train)
        coef = np.abs(np.asarray(clf.coef_, dtype=np.float64))
        if coef.ndim == 1:
            score = coef
        else:
            score = coef.max(axis=0)
        score = np.nan_to_num(score, nan=0.0, posinf=0.0, neginf=0.0)
        idx = np.flatnonzero(score > 1e-8).astype(np.int32, copy=False)
        if idx.size < min_keep:
            order = np.argsort(-score, kind="mergesort")
            keep = min(max(min_keep, 1), n_feat)
            idx = order[:keep].astype(np.int32, copy=False)
        idx = np.unique(idx)
        idx = idx[np.argsort(-score[idx], kind="mergesort")]
        names = [feature_names[int(i)] for i in idx.tolist()]
        return SelectionResult(
            selected_idx=idx,
            selected_feature_names=names,
            meta={"selector": "l1_nonzero", "selected_count": int(idx.size), "l1_c": c},
            score_vector=score,
        )

    if method == "mi_topk":
        topk = int(fs_params.get("fs_topk", 128))
        topk = int(max(1, min(topk, n_feat)))
        mi = mutual_info_classif(x_train, y_train, random_state=int(seed))
        mi = np.nan_to_num(np.asarray(mi, dtype=np.float64), nan=0.0, posinf=0.0, neginf=0.0)
        order = np.argsort(-mi, kind="mergesort")
        idx = order[:topk].astype(np.int32, copy=False)
        names = [feature_names[int(i)] for i in idx.tolist()]
        return SelectionResult(
            selected_idx=idx,
            selected_feature_names=names,
            meta={"selector": "mi_topk", "selected_count": int(idx.size), "topk": topk},
            score_vector=mi,
        )

    if method == "tree_topk":
        topk = int(fs_params.get("fs_topk", 128))
        topk = int(max(1, min(topk, n_feat)))
        imp = _fit_selector_tree(
            x_train=x_train,
            y_train=y_train,
            head_name=head_name,
            gpu_devices=gpu_devices,
            seed=seed,
        )
        imp = np.nan_to_num(imp, nan=0.0, posinf=0.0, neginf=0.0)
        order = np.argsort(-imp, kind="mergesort")
        idx = order[:topk].astype(np.int32, copy=False)
        names = [feature_names[int(i)] for i in idx.tolist()]
        return SelectionResult(
            selected_idx=idx,
            selected_feature_names=names,
            meta={"selector": "tree_topk", "selected_count": int(idx.size), "topk": topk},
            score_vector=imp,
        )

    raise ValueError(f"Unknown feature selection method: {method}")


def _fit_head_model(
    *,
    x_train: np.ndarray,
    y_train: np.ndarray,
    head_name: str,
    cb_params: dict[str, Any],
    gpu_devices: str,
    seed: int,
) -> CatBoostClassifier | ConstantModel:
    uniq = np.unique(y_train)
    if uniq.size < 2:
        cls = np.array(sorted(int(v) for v in uniq.tolist()), dtype=np.int32)
        probs = np.array([1.0], dtype=np.float32)
        return ConstantModel(classes_=cls, class_probs_=probs)

    loss_function = "MultiClass" if head_name == "breakfree" else "Logloss"
    model = CatBoostClassifier(
        loss_function=loss_function,
        depth=int(cb_params["cb_depth"]),
        learning_rate=float(cb_params["cb_learning_rate"]),
        l2_leaf_reg=float(cb_params["cb_l2_leaf_reg"]),
        iterations=int(cb_params["cb_iterations"]),
        random_strength=float(cb_params["cb_random_strength"]),
        subsample=float(cb_params["cb_subsample"]),
        bootstrap_type="Bernoulli",
        task_type="GPU",
        devices=str(gpu_devices),
        random_seed=int(seed),
        allow_writing_files=False,
        verbose=False,
    )
    model.fit(x_train, y_train)
    return model


def _predict_proba_fixed(
    model: CatBoostClassifier | ConstantModel,
    x: np.ndarray,
    n_classes_expected: int,
) -> np.ndarray:
    raw = model.predict_proba(x)
    if raw.ndim == 1:
        raw = raw.reshape(-1, 1)

    classes = np.asarray(getattr(model, "classes_", np.arange(raw.shape[1])), dtype=np.int32)
    out = np.zeros((x.shape[0], n_classes_expected), dtype=np.float32)
    for col_idx, cls in enumerate(classes.tolist()):
        if 0 <= int(cls) < n_classes_expected:
            out[:, int(cls)] = raw[:, col_idx].astype(np.float32, copy=False)

    s = out.sum(axis=1, keepdims=True)
    s[s <= 0] = 1.0
    out = out / s
    return out.astype(np.float32, copy=False)


def _build_trial_param_spaces(trial: optuna.Trial, feature_methods: list[str], lookback_grid: list[int]) -> dict[str, Any]:
    params: dict[str, Any] = {}
    params["lookback_batches"] = trial.suggest_categorical("lookback_batches", lookback_grid)
    params["fs_method"] = trial.suggest_categorical("fs_method", feature_methods)
    params["cb_depth"] = trial.suggest_int("cb_depth", 3, 8)
    params["cb_learning_rate"] = trial.suggest_float("cb_learning_rate", 0.01, 0.2, log=True)
    params["cb_l2_leaf_reg"] = trial.suggest_float("cb_l2_leaf_reg", 1.0, 30.0, log=True)
    params["cb_iterations"] = trial.suggest_int("cb_iterations", 80, 400)
    params["cb_random_strength"] = trial.suggest_float("cb_random_strength", 0.0, 3.0)
    params["cb_subsample"] = trial.suggest_float("cb_subsample", 0.6, 1.0)

    if params["fs_method"] == "l1_nonzero":
        params["fs_l1_c"] = trial.suggest_float("fs_l1_c", 1e-2, 20.0, log=True)
        params["fs_min_keep"] = trial.suggest_categorical("fs_min_keep", [8, 16, 24, 32])
    elif params["fs_method"] in {"mi_topk", "tree_topk"}:
        params["fs_topk"] = trial.suggest_categorical("fs_topk", TOPK_GRID)
    return params


def _evaluate_head_proxy_cost(head_name: str, y_true: np.ndarray, y_pred: np.ndarray) -> float:
    if y_true.size == 0:
        return 0.0
    if head_name == "breakfree":
        return float(_compute_custom_cost(y_true, y_pred)["mean_cost"])
    # 4dir: opposite direction mismatch costs 2, correct 0.
    wrong = (y_true != y_pred).astype(np.float64)
    return float((2.0 * wrong).mean())


def _run_head_optuna(
    *,
    head_name: str,
    x: np.ndarray,
    y: np.ndarray,
    feature_names: list[str],
    batch_order: list[int],
    batch_ranges: dict[int, tuple[int, int]],
    current_batch_idx: int,
    val_tail_ratio: float,
    lookback_grid: list[int],
    feature_methods: list[str],
    n_trials: int,
    trial_failure_policy: str,
    selector_warning_policy: str,
    gpu_devices: str,
    seed: int,
) -> tuple[optuna.Study, list[dict[str, Any]]]:
    optuna.logging.set_verbosity(optuna.logging.WARNING)
    trial_rows: list[dict[str, Any]] = []
    history_len = int(current_batch_idx)
    feasible_lookback_grid = _resolve_feasible_lookback_grid(lookback_grid, history_len)
    if not feasible_lookback_grid:
        raise RuntimeError(
            f"No feasible lookback values for head={head_name} at current_batch_idx={current_batch_idx}."
        )

    def objective(trial: optuna.Trial) -> float:
        params = _build_trial_param_spaces(trial, feature_methods, feasible_lookback_grid)
        lookback_requested_batches = int(params["lookback_batches"])
        history_batches = _get_batch_window(
            batch_order=batch_order,
            current_batch_idx=current_batch_idx,
            lookback_batches=lookback_requested_batches,
        )
        lookback_effective_batches = int(len(history_batches))
        trial.set_user_attr("lookback_requested_batches", int(lookback_requested_batches))
        trial.set_user_attr("lookback_effective_batches", int(lookback_effective_batches))
        trial.set_user_attr("lookback_batches", int(lookback_effective_batches))

        try:
            train_batches, val_batches = _split_train_val_batches(history_batches, val_tail_ratio)
            if not train_batches or not val_batches:
                raise optuna.TrialPruned("insufficient history for train/val split")

            idx_train = _batches_to_indices(batch_ranges, train_batches)
            idx_val = _batches_to_indices(batch_ranges, val_batches)
            if idx_train.size < 32 or idx_val.size < 16:
                raise optuna.TrialPruned("too few train/val samples")

            y_train = y[idx_train]
            y_val = y[idx_val]
            if np.unique(y_train).size < 2 or np.unique(y_val).size < 2:
                raise optuna.TrialPruned("insufficient class diversity")

            fs_method = str(params["fs_method"])
            with warnings.catch_warnings(record=True) as caught_warnings:
                warnings.simplefilter("always", category=ConvergenceWarning)
                selector = _select_features(
                    method=fs_method,
                    x_train=x[idx_train],
                    y_train=y_train,
                    feature_names=feature_names,
                    seed=seed + int(current_batch_idx),
                    head_name=head_name,
                    gpu_devices=gpu_devices,
                    fs_params=params,
                )
            if (
                selector_warning_policy == "prune_on_convergence_warning"
                and any(issubclass(w.category, ConvergenceWarning) for w in caught_warnings)
            ):
                trial.set_user_attr(
                    "failure_reason",
                    "ConvergenceWarning in selector; pruned by selector_warning_policy.",
                )
                raise optuna.TrialPruned("selector_convergence_warning")

            if selector.selected_idx.size < 2:
                raise optuna.TrialPruned("too few features after selection")

            x_train_sel = x[idx_train][:, selector.selected_idx]
            x_val_sel = x[idx_val][:, selector.selected_idx]

            model = _fit_head_model(
                x_train=x_train_sel,
                y_train=y_train,
                head_name=head_name,
                cb_params=params,
                gpu_devices=gpu_devices,
                seed=seed + 17 * int(current_batch_idx) + (0 if head_name == "breakfree" else 1),
            )
            n_cls = 3 if head_name == "breakfree" else 2
            p_val = _predict_proba_fixed(model, x_val_sel, n_classes_expected=n_cls)
            pred_val = np.argmax(p_val, axis=1).astype(np.int16, copy=False)

            macro = float(f1_score(y_val, pred_val, average="macro"))
            proxy_cost = _evaluate_head_proxy_cost(head_name, y_val, pred_val)
            objective_score = macro - 1e-3 * proxy_cost

            trial.set_user_attr("macro_f1", macro)
            trial.set_user_attr("proxy_cost", proxy_cost)
            trial.set_user_attr("selected_feature_count", int(selector.selected_idx.size))
            trial.set_user_attr("train_rows", int(idx_train.size))
            trial.set_user_attr("val_rows", int(idx_val.size))
            trial.set_user_attr("train_start_batch", int(train_batches[0]))
            trial.set_user_attr("train_end_batch", int(train_batches[-1]))
            trial.set_user_attr("val_start_batch", int(val_batches[0]))
            trial.set_user_attr("val_end_batch", int(val_batches[-1]))
            trial.set_user_attr("failure_reason", None)
            return float(objective_score)
        except optuna.TrialPruned as exc:
            if trial.user_attrs.get("failure_reason") is None:
                trial.set_user_attr("failure_reason", str(exc))
            raise
        except Exception as exc:
            msg = f"{type(exc).__name__}: {exc}"
            trial.set_user_attr("failure_reason", msg)
            if trial_failure_policy == "prune_fallback":
                raise optuna.TrialPruned(f"trial_exception: {msg}") from exc
            raise

    sampler = optuna.samplers.TPESampler(seed=seed + 97 * int(current_batch_idx) + (0 if head_name == "breakfree" else 100000))
    study = optuna.create_study(direction="maximize", sampler=sampler)
    study.optimize(objective, n_trials=int(n_trials), show_progress_bar=False)

    for tr in study.trials:
        row = {
            "head": head_name,
            "pred_batch_idx": int(current_batch_idx),
            "trial_number": int(tr.number),
            "state": str(tr.state.name),
            "objective": _safe_float(tr.value),
            "params_json": json.dumps(dict(tr.params), ensure_ascii=False),
            "macro_f1": _safe_float(tr.user_attrs.get("macro_f1")),
            "proxy_cost": _safe_float(tr.user_attrs.get("proxy_cost")),
            "selected_feature_count": int(tr.user_attrs.get("selected_feature_count", 0)),
            "train_rows": int(tr.user_attrs.get("train_rows", 0)),
            "val_rows": int(tr.user_attrs.get("val_rows", 0)),
            "lookback_batches": int(tr.user_attrs.get("lookback_batches", -1)),
            "lookback_requested_batches": int(
                tr.user_attrs.get("lookback_requested_batches", tr.params.get("lookback_batches", -1))
            ),
            "lookback_effective_batches": int(
                tr.user_attrs.get("lookback_effective_batches", tr.user_attrs.get("lookback_batches", -1))
            ),
            "train_start_batch": tr.user_attrs.get("train_start_batch"),
            "train_end_batch": tr.user_attrs.get("train_end_batch"),
            "val_start_batch": tr.user_attrs.get("val_start_batch"),
            "val_end_batch": tr.user_attrs.get("val_end_batch"),
            "failure_reason": tr.user_attrs.get("failure_reason"),
        }
        trial_rows.append(row)
    return study, trial_rows


def _fallback_trial_params() -> dict[str, Any]:
    return {
        "lookback_batches": -1,
        "fs_method": "none",
        "cb_depth": 4,
        "cb_learning_rate": 0.05,
        "cb_l2_leaf_reg": 3.0,
        "cb_iterations": 200,
        "cb_random_strength": 0.0,
        "cb_subsample": 0.8,
    }


def _resolve_best_trial_or_fallback(
    study: optuna.Study,
    *,
    head_name: str,
    pred_batch: int,
    trial_failure_policy: str,
) -> tuple[dict[str, Any], dict[str, Any], optuna.trial.FrozenTrial | None]:
    complete = [t for t in study.trials if t.state == optuna.trial.TrialState.COMPLETE]
    if complete:
        best = study.best_trial
        return dict(best.params), {
            "used_fallback": False,
            "fallback_reason": None,
            "best_trial_number": int(best.number),
            "best_objective": _safe_float(best.value),
            "best_macro_f1": _safe_float(best.user_attrs.get("macro_f1")),
            "best_proxy_cost": _safe_float(best.user_attrs.get("proxy_cost")),
        }, best

    if trial_failure_policy != "prune_fallback":
        raise RuntimeError(f"No complete Optuna trials for head={head_name} at pred_batch={pred_batch}.")

    return _fallback_trial_params(), {
        "used_fallback": True,
        "fallback_reason": "no_complete_trials",
        "best_trial_number": None,
        "best_objective": None,
        "best_macro_f1": None,
        "best_proxy_cost": None,
    }, None


def _refit_head_from_params(
    *,
    head_name: str,
    params: dict[str, Any],
    x: np.ndarray,
    y: np.ndarray,
    feature_names: list[str],
    batch_order: list[int],
    batch_ranges: dict[int, tuple[int, int]],
    current_batch_idx: int,
    val_tail_ratio: float,
    gpu_devices: str,
    seed: int,
) -> tuple[CatBoostClassifier | ConstantModel, SelectionResult, dict[str, Any], np.ndarray]:
    lookback_requested_batches = int(params.get("lookback_batches", -1))
    history_batches = _get_batch_window(
        batch_order=batch_order,
        current_batch_idx=current_batch_idx,
        lookback_batches=lookback_requested_batches,
    )
    lookback_effective_batches = int(len(history_batches))
    train_batches, val_batches = _split_train_val_batches(history_batches, val_tail_ratio)
    history_idx = _batches_to_indices(batch_ranges, history_batches)
    if history_idx.size == 0:
        raise RuntimeError("History is empty during refit.")

    y_hist = y[history_idx]
    if np.unique(y_hist).size < 2:
        # Constant fallback.
        cls = np.array(sorted(np.unique(y_hist).tolist()), dtype=np.int32)
        probs = np.array([1.0], dtype=np.float32)
        model: CatBoostClassifier | ConstantModel = ConstantModel(classes_=cls, class_probs_=probs)
        sel = SelectionResult(
            selected_idx=np.arange(x.shape[1], dtype=np.int32),
            selected_feature_names=feature_names.copy(),
            meta={"selector": "none", "selected_count": int(x.shape[1]), "constant_model_fallback": True},
            score_vector=None,
        )
        refit_meta = {
            "lookback_requested_batches": int(lookback_requested_batches),
            "lookback_effective_batches": int(lookback_effective_batches),
            "lookback_batches": int(lookback_effective_batches),
            "history_start_batch": int(history_batches[0]),
            "history_end_batch": int(history_batches[-1]),
            "train_start_batch": int(train_batches[0]) if train_batches else None,
            "train_end_batch": int(train_batches[-1]) if train_batches else None,
            "val_start_batch": int(val_batches[0]) if val_batches else None,
            "val_end_batch": int(val_batches[-1]) if val_batches else None,
            "history_rows": int(history_idx.size),
            "constant_fallback": True,
        }
        return model, sel, refit_meta, history_idx

    fs_method = str(params.get("fs_method", "none"))
    selector = _select_features(
        method=fs_method,
        x_train=x[history_idx],
        y_train=y_hist,
        feature_names=feature_names,
        seed=seed + 13 * int(current_batch_idx),
        head_name=head_name,
        gpu_devices=gpu_devices,
        fs_params=params,
    )
    x_hist_sel = x[history_idx][:, selector.selected_idx]

    model = _fit_head_model(
        x_train=x_hist_sel,
        y_train=y_hist,
        head_name=head_name,
        cb_params=params,
        gpu_devices=gpu_devices,
        seed=seed + 19 * int(current_batch_idx) + (0 if head_name == "breakfree" else 1),
    )

    refit_meta = {
        "lookback_requested_batches": int(lookback_requested_batches),
        "lookback_effective_batches": int(lookback_effective_batches),
        "lookback_batches": int(lookback_effective_batches),
        "history_start_batch": int(history_batches[0]),
        "history_end_batch": int(history_batches[-1]),
        "train_start_batch": int(train_batches[0]) if train_batches else None,
        "train_end_batch": int(train_batches[-1]) if train_batches else None,
        "val_start_batch": int(val_batches[0]) if val_batches else None,
        "val_end_batch": int(val_batches[-1]) if val_batches else None,
        "history_rows": int(history_idx.size),
        "constant_fallback": bool(isinstance(model, ConstantModel)),
    }
    return model, selector, refit_meta, history_idx


